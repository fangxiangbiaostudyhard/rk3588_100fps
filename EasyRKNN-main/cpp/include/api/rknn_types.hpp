enum class ErrorCode : int {
    Success = 0,
    InvalidArgument = -1,
    ModelNotFound = -2,
    ModelAlreadyExists = -3,
    InferenceFailed = -4,
    OutOfMemory = -5,
    FileNotExist = -6,
    InitFailed = -7,
    UnsupportedModelType = -8,
    PoolExhausted = -9,
    QueueFull = -10,
    UnsupportedLayout = -11,
    Unknown = -99
};

inline const char* GetErrorString(ErrorCode code) {
    switch (code) {
        case ErrorCode::Success: return "Success";
        case ErrorCode::InvalidArgument: return "Invalid argument";
        case ErrorCode::ModelNotFound: return "Model not found";
        case ErrorCode::ModelAlreadyExists: return "Model already exists";
        case ErrorCode::InferenceFailed: return "Inference failed";
        case ErrorCode::OutOfMemory: return "Out of memory";
        case ErrorCode::FileNotExist: return "File does not exist";
        case ErrorCode::InitFailed: return "Initialization failed";
        case ErrorCode::UnsupportedModelType: return "Unsupported model type";
        case ErrorCode::PoolExhausted: return "Pool exhausted";
        case ErrorCode::QueueFull: return "Task queue full";
        case ErrorCode::UnsupportedLayout: return "Unsupported tensor/image layout";
        default: return "Unknown error";
    }
}

enum class ModelType : int {
    YOLOV5 = 0, YOLOV7 = 1, YOLOV8 = 2, YOLOV8_SEG = 3, YOLOV8_POSE = 4,
    YOLOV9 = 5, YOLOV10 = 6, YOLOV11 = 7, CLASSIFICATION = 8, CUSTOM = 99
};

inline const char* GetModelTypeString(ModelType type) {
    switch (type) {
        case ModelType::YOLOV5: return "YOLOv5";
        case ModelType::YOLOV7: return "YOLOv7";
        case ModelType::YOLOV8: return "YOLOv8";
        case ModelType::YOLOV8_SEG: return "YOLOv8-Seg";
        case ModelType::YOLOV8_POSE: return "YOLOv8-Pose";
        case ModelType::YOLOV9: return "YOLOv9";
        case ModelType::YOLOV10: return "YOLOv10";
        case ModelType::YOLOV11: return "YOLOv11";
        case ModelType::CLASSIFICATION: return "Classification";
        case ModelType::CUSTOM: return "Custom";
        default: return "Unknown";
    }
}

// Source pixel layouts understood by the RGA zero-copy preprocessor.
enum class PixelFormat : int {
    BGR888 = 0,
    RGB888 = 1,
    NV12 = 2,
    NV21 = 3,
};

enum class ResizeMode : int {
    Stretch = 0,   // fastest; exact behavior of the original EasyRKNN demo
    Letterbox = 1  // preserves aspect ratio; closer to Ultralytics preprocessing
};

struct BBox {
    float left = 0;
    float top = 0;
    float right = 0;
    float bottom = 0;
    float Width() const { return right - left; }
    float Height() const { return bottom - top; }
    float Area() const { return std::max(0.0f, Width()) * std::max(0.0f, Height()); }
    float CenterX() const { return (left + right) / 2.0f; }
    float CenterY() const { return (top + bottom) / 2.0f; }
};

struct Keypoint { float x = 0; float y = 0; float confidence = 0; };

struct Detection {
    int label_id = -1;
    float score = 0;
    BBox bbox;
    std::string label_name;
    std::vector<std::vector<int>> contour_points;
    std::vector<Keypoint> keypoints;
    float mask_area = 0;
    bool HasContour() const { return !contour_points.empty(); }
    bool HasKeypoints() const { return !keypoints.empty(); }
};

struct DetectionResult {
    std::vector<Detection> detections;
    int image_width = 0;
    int image_height = 0;
    float inference_time_ms = 0;   // end-to-end request latency inside Detect()
    ErrorCode error_code = ErrorCode::Success;
    std::string error_message;
    uint64_t request_id = 0;
    int source_id = -1;
    bool IsSuccess() const { return error_code == ErrorCode::Success; }
    int Count() const { return static_cast<int>(detections.size()); }
};

/**
 * External DMA-BUF image. The SDK does not own fd in synchronous calls.
 * For async calls the detector duplicates the fd and closes the duplicate after completion.
 */
struct DmaBufImage {
    int fd = -1;
    void* virt_addr = nullptr;  // optional; not required for zero-copy RGA path
    int width = 0;
    int height = 0;
    int w_stride = 0;           // pixels; 0 = width
    int h_stride = 0;           // pixels; 0 = height
    PixelFormat format = PixelFormat::NV12;

    bool Valid() const { return fd >= 0 && width > 0 && height > 0; }
};

/** Coordinate mapping generated by preprocessing. */
struct PreprocessMeta {
    int src_width = 0;
    int src_height = 0;
    int dst_width = 0;
    int dst_height = 0;
    float scale_x = 1.0f;
    float scale_y = 1.0f;
    int pad_left = 0;
    int pad_top = 0;
    ResizeMode mode = ResizeMode::Stretch;

    float ToSourceX(float x) const { return (x - static_cast<float>(pad_left)) / scale_x; }
    float ToSourceY(float y) const { return (y - static_cast<float>(pad_top)) / scale_y; }
};

struct ImageData {
    uint8_t* data = nullptr;
    int width = 0;
    int height = 0;
    int channels = 3;
    int stride = 0;
    ImageData() = default;
    ImageData(uint8_t* d, int w, int h, int c = 3, int s = 0)
        : data(d), width(w), height(h), channels(c), stride(s ? s : w * c) {}
};

struct ModelConfig {
    std::string model_path;
    std::string labels_path;
    ModelType type = ModelType::YOLOV5;
    int pool_size = 3;            // number of RKNN contexts, NOT physical NPU core count
    float nms_threshold = 0.45f;
    float conf_threshold = 0.25f;
    int input_width = 0;
    int input_height = 0;
    ResizeMode resize_mode = ResizeMode::Stretch;
    bool zero_copy_io = true;
};

struct PoolInfo {
    int max_size = 0;
    int active_count = 0;
    int idle_count = 0;
};

struct ModelInfo {
    std::string name;
    std::string path;
    ModelType type = ModelType::CUSTOM;
    PoolInfo pool_info;
    int input_width = 0;
    int input_height = 0;
    int input_channels = 0;
    int num_classes = 0;
    bool zero_copy_io = false;
};

inline ImageData MakeImage(uint8_t* data, int width, int height, int channels = 3) {
    return ImageData(data, width, height, channels);
}

inline bool IsValidDetection(const Detection& det, int img_width, int img_height) {
    if (det.score < 0 || det.score > 1.0f) return false;
    if (det.bbox.left < 0 || det.bbox.top < 0) return false;
    if (det.bbox.right > img_width || det.bbox.bottom > img_height) return false;
    return det.bbox.Width() > 0 && det.bbox.Height() > 0;
}

inline float CalculateIoU(const BBox& a, const BBox& b) {
    float inter_left = std::max(a.left, b.left);
    float inter_top = std::max(a.top, b.top);
    float inter_right = std::min(a.right, b.right);
    float inter_bottom = std::min(a.bottom, b.bottom);
    if (inter_right <= inter_left || inter_bottom <= inter_top) return 0.0f;
    float inter_area = (inter_right - inter_left) * (inter_bottom - inter_top);
    float union_area = a.Area() + b.Area() - inter_area;
    return union_area > 0 ? inter_area / union_area : 0.0f;
}

